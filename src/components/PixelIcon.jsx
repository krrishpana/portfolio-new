export default function PixelIcon({ name, size = 20, className = "", title }) {
  const ic = ICONS[name];
  if (!ic) return null;
  const h = ic.map.length, w = ic.map[0].length;
  const rects = [];
  ic.map.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      if (ic.c[ch]) rects.push(<rect key={`${x}-${y}`} x={x} y={y} width="1.03" height="1.03" fill={ic.c[ch]} />);
    })
  );
  return (
    <svg
      className={`pixel-icon ${className}`}
      viewBox={`0 0 ${w} ${h}`}
      width={size}
      height={(size * h) / w}
      shapeRendering="crispEdges"
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
    >
      {title && <title>{title}</title>}
      {rects}
    </svg>
  );
}
